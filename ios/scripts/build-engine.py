#!/usr/bin/env python3
"""Build HandBrake's actual libhb and pinned contribs for iOS on a Mac.

Use --plan on any host to inspect targets without an Apple SDK. The normal
build runs configure/make, verifies an engine link, and packages an XCFramework;
no desktop executable is used by the iOS application.
"""

import argparse
from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import shlex
import shutil
import struct
import subprocess
import sys
import tempfile


REPOSITORY = Path(__file__).resolve().parents[2]
PACKAGES = (
    "libass", "libavformat", "libavfilter", "libavcodec", "libavutil",
    "libswresample", "libswscale", "dvdnav", "dvdread", "theoraenc",
    "theoradec", "vorbis", "vorbisenc", "ogg", "x264", "libbluray",
    "jansson", "libturbojpeg", "SvtAv1Enc", "x265",
)
X265_BIT_DEPTHS = (8, 10, 12)
FRAMEWORKS = (
    "Foundation", "CoreFoundation", "CoreGraphics", "CoreText", "AudioToolbox",
    "VideoToolbox", "CoreMedia", "CoreVideo", "IOSurface", "Metal", "Accelerate", "QuartzCore",
)
SYSTEM_LIBRARIES = {"c", "c++", "m", "pthread", "iconv", "z", "bz2", "System"}


@dataclass(frozen=True)
class Target:
    sdk: str
    arch: str
    minimum: str

    @property
    def identifier(self):
        return f"{self.sdk}-{self.arch}"

    @property
    def triple(self):
        suffix = "-simulator" if self.sdk == "iphonesimulator" else ""
        return f"{self.arch}-apple-ios{self.minimum}{suffix}"


def run(command, *, cwd=None, env=None, capture=False):
    print("+ " + shlex.join(str(value) for value in command), flush=True)
    result = subprocess.run(
        [str(value) for value in command], cwd=cwd, env=env, check=True,
        text=True, stdout=subprocess.PIPE if capture else None,
    )
    return result.stdout.strip() if capture else None


def xcrun(sdk, *arguments):
    return run(["xcrun", "--sdk", sdk, *arguments], capture=True)


def write_text(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(value)


def make_wrapper(path, executable, arguments=(), *, unset_environment=()):
    script = "#!/bin/sh\n"
    if unset_environment:
        script += "unset " + shlex.join(unset_environment) + "\n"
    write_text(path, script + "exec " + shlex.join([executable, *arguments]) + ' "$@"\n')
    path.chmod(0o755)


def cmake_quote(value):
    return str(value).replace("\\", "/").replace('"', '\\"')


def write_engine_module(headers):
    # SwiftPM's binary target imports this narrow C API module. An umbrella
    # directory would also import unrelated FFmpeg/dependency implementation
    # headers, whose compiler configuration differs from app code.
    write_text(headers / "HandBrakeEngine.h", """/* SPDX-License-Identifier: GPL-2.0-or-later */
#ifndef HB_IOS_ENGINE_MODULE_H
#define HB_IOS_ENGINE_MODULE_H
#include <handbrake/handbrake.h>
#endif
""")
    write_text(headers / "module.modulemap", """module HandBrakeEngine {
    header "HandBrakeEngine.h"
    export *
}
""")


def toolchain_files(directory, target, sdk_root, clang, clangxx, ar, ranlib, pkgconfig):
    tools = directory / "tools"
    tools.mkdir(parents=True, exist_ok=True)
    target_flags = ["-target", target.triple, "-isysroot", str(sdk_root)]
    make_wrapper(tools / "hb-clang", clang, target_flags)
    make_wrapper(tools / "hb-clang++", clangxx, target_flags)
    # Meson and dependency scripts sometimes explicitly select 'clang'. Put
    # target wrappers first in PATH as well as passing CC/CXX.
    make_wrapper(tools / "clang", clang, target_flags)
    make_wrapper(tools / "clang++", clangxx, target_flags)
    cc, cxx = tools / "hb-clang", tools / "hb-clang++"
    cmake = directory / "ios.toolchain.cmake"
    write_text(cmake, "\n".join([
        "# Generated by ios/scripts/build-engine.py",
        "set(CMAKE_SYSTEM_NAME iOS)",
        f'set(CMAKE_SYSTEM_PROCESSOR "{target.arch}")',
        f'set(CMAKE_OSX_ARCHITECTURES "{target.arch}" CACHE STRING "" FORCE)',
        f'set(CMAKE_OSX_SYSROOT "{cmake_quote(sdk_root)}" CACHE PATH "" FORCE)',
        f'set(CMAKE_OSX_DEPLOYMENT_TARGET "{target.minimum}" CACHE STRING "" FORCE)',
        f'set(CMAKE_C_COMPILER "{cmake_quote(cc)}")',
        f'set(CMAKE_CXX_COMPILER "{cmake_quote(cxx)}")',
        f'set(CMAKE_ASM_COMPILER "{cmake_quote(cc)}")',
        f'set(CMAKE_AR "{cmake_quote(ar)}")',
        f'set(CMAKE_RANLIB "{cmake_quote(ranlib)}")',
        "set(CMAKE_TRY_COMPILE_TARGET_TYPE STATIC_LIBRARY)",
        "set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)",
        "set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)",
        "set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)",
        "set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)",
        "",
    ]))
    meson = directory / "ios.cross.meson"
    # repr produces valid quoted Meson strings for normal POSIX paths.
    cpu_family = "aarch64" if target.arch == "arm64" else "x86_64"
    prefix = directory / "contrib"
    write_text(meson, "\n".join([
        "# Generated by ios/scripts/build-engine.py", "[binaries]",
        f"c = {str(cc)!r}", f"cpp = {str(cxx)!r}", f"ar = {str(ar)!r}",
        f"strip = {xcrun(target.sdk, '--find', 'strip')!r}",
        f"pkg-config = {str(pkgconfig)!r}",
        "[host_machine]", "system = 'darwin'",
        f"cpu_family = '{cpu_family}'", f"cpu = '{target.arch}'", "endian = 'little'",
        "[properties]", "needs_exe_wrapper = true",
        f"sys_root = {str(sdk_root)!r}", f"pkg_config_libdir = {str(prefix / 'lib/pkgconfig')!r}",
        "[built-in options]", "default_library = 'static'", "b_staticpic = true", "",
    ]))
    return tools, cc, cxx, cmake, meson


def host_compiler_wrappers(directory, sdk_root, clang, clangxx):
    # bin2c runs on the build Mac. Xcode clang does not reliably discover system
    # headers after SDKROOT is cleared, so give native helpers an explicit macOS
    # SDK while keeping target iOS flags out of their compilation.
    tools = directory / "tools"
    cc, cxx = tools / "hb-host-clang", tools / "hb-host-clang++"
    for compiler, executable in ((cc, clang), (cxx, clangxx)):
        make_wrapper(compiler, executable, ["-isysroot", str(sdk_root)],
                     unset_environment=("IPHONEOS_DEPLOYMENT_TARGET", "IPHONESIMULATOR_DEPLOYMENT_TARGET"))
    return cc, cxx


def dependency_archives(directory, env):
    flags = shlex.split(run(["pkg-config", "--static", "--libs", *PACKAGES], env=env, capture=True))
    library_dir = directory / "contrib/lib"
    archives = [directory / "libhb/libhandbrake.a"]
    for flag in flags:
        if not flag.startswith("-l"):
            continue
        name = flag[2:]
        archive = library_dir / f"lib{name}.a"
        if archive.is_file():
            if archive not in archives:
                archives.append(archive)
        elif name not in SYSTEM_LIBRARIES:
            raise RuntimeError(f"No target static archive for {flag}: {archive}")
    for archive in archives:
        if not archive.is_file():
            raise RuntimeError(f"Missing engine dependency: {archive}")
    return archives, flags


def verify_archive_platform(archive, target):
    """Check every Mach-O member, including assembler objects, before packaging.

    lipo alone cannot distinguish arm64 macOS, iOS, and iOS Simulator objects.
    Parse ar/Mach-O directly so the verifier is also testable without Apple tools.
    """
    data = Path(archive).read_bytes()
    if not data.startswith(b"!<arch>\n"):
        raise RuntimeError(f"Not a regular static archive: {archive}")
    offset, objects = 8, 0
    expected_cpu = 0x100000C if target.arch == "arm64" else 0x1000007
    expected_platform = 2 if target.sdk == "iphoneos" else 7
    while offset < len(data):
        header = data[offset:offset + 60]
        if len(header) != 60 or header[58:60] != b"`\n":
            raise RuntimeError(f"Malformed static archive: {archive}")
        size = int(header[48:58].strip())
        name = header[:16].decode("ascii").strip()
        member = data[offset + 60:offset + 60 + size]
        offset += 60 + size + (size % 2)
        if name.startswith("#1/"):
            length = int(name[3:])
            name, member = member[:length].decode("utf-8").rstrip("\x00"), member[length:]
        if name.startswith("__.SYMDEF") or name in ("/", "//", "/SYM64/"):
            continue
        if member[:4] == b"\xcf\xfa\xed\xfe":
            endian, header_size = "<", 32
        elif member[:4] == b"\xfe\xed\xfa\xcf":
            endian, header_size = ">", 32
        elif member[:4] == b"\xce\xfa\xed\xfe":
            endian, header_size = "<", 28
        elif member[:4] == b"\xfe\xed\xfa\xce":
            endian, header_size = ">", 28
        else:
            raise RuntimeError(f"Non-Mach-O object in {archive}: {name}")
        cpu = struct.unpack_from(endian + "I", member, 4)[0]
        count = struct.unpack_from(endian + "I", member, 16)[0]
        if cpu != expected_cpu:
            raise RuntimeError(f"Wrong architecture in {archive} member {name}: {cpu:#x}")
        cursor, found = header_size, False
        for _ in range(count):
            command, command_size = struct.unpack_from(endian + "II", member, cursor)
            if command_size < 8 or cursor + command_size > len(member):
                raise RuntimeError(f"Malformed Mach-O load commands: {archive} member {name}")
            if command == 0x32:  # LC_BUILD_VERSION
                actual = struct.unpack_from(endian + "I", member, cursor + 8)[0]
                if actual != expected_platform:
                    raise RuntimeError(f"Wrong Apple platform in {archive} member {name}: {actual}, expected {expected_platform}")
                found = True
            elif command == 0x24:  # LC_VERSION_MIN_MACOSX
                raise RuntimeError(f"macOS object in iOS archive {archive}: {name}")
            elif command == 0x25:  # Legacy LC_VERSION_MIN_IPHONEOS
                if target.arch == "arm64" and target.sdk == "iphonesimulator":
                    raise RuntimeError(f"Device object in arm64 simulator archive {archive}: {name}")
                found = True
            cursor += command_size
        if not found:
            raise RuntimeError(f"Missing Apple platform metadata in {archive}: {name}")
        objects += 1
    if not objects:
        raise RuntimeError(f"No Mach-O objects in {archive}")
    return objects


def verify_x265_multilib(archive, target):
    """Require definitions from each statically linked x265 bit-depth variant.

    The 8-bit public API delegates to C++ namespace APIs for 10/12-bit. Checking
    definitions (nm -U excludes undefined references) catches an incomplete
    multilib archive even when the generic public x265 API still links.
    """
    symbols = run(["xcrun", "--sdk", target.sdk, "nm", "-gU", archive], capture=True)
    defined = {line.split()[-1] for line in symbols.splitlines() if line.strip()}
    expected = {
        "_x265_api_query": 8,
        "__ZN10x265_10bit14x265_api_queryEiiPi": 10,
        "__ZN10x265_12bit14x265_api_queryEiiPi": 12,
    }
    for symbol, depth in expected.items():
        if symbol not in defined:
            raise RuntimeError(f"Missing statically linked {depth}-bit x265 API in {archive}: {symbol}")


def link_smoke(directory, target, cc, env, archive, headers, dependency_flags):
    source = directory / "engine-link-smoke.m"
    write_text(source, """#include <handbrake/handbrake.h>
#include <x265.h>
int main(void)
{
    const int depths[] = {8, 10, 12};
    for (unsigned i = 0; i < sizeof(depths) / sizeof(depths[0]); i++)
    {
        int error = 0;
        const x265_api *api = x265_api_query(depths[i], X265_BUILD, &error);
        if (!api || api->bit_depth != depths[i] || api->api_build_number != X265_BUILD) return 2;
        x265_param *param = api->param_alloc();
        if (!param) return 3;
        api->param_free(param);
    }
    hb_global_init();
    hb_handle_t *handle = hb_init(0);
    if (!handle) return 1;
    hb_close(&handle);
    hb_global_close();
    return 0;
}
""")
    # Linking (without executing) catches missing objects/frameworks before the
    # app build. C++ runtime is needed by zimg/harfbuzz/SVT-AV1.
    command = [cc, "-fblocks", "-I", headers, source, archive, "-o", directory / "engine-link-smoke"]
    command.extend(["-lc++", "-liconv", "-lz", "-lbz2"])
    for framework in FRAMEWORKS:
        command.extend(["-framework", framework])
    # Keep any framework/driver options declared in .pc files, but do not link
    # the static dependencies again after they have been merged.
    index = 0
    while index < len(dependency_flags):
        flag = dependency_flags[index]
        if flag == "-framework":
            framework = dependency_flags[index + 1]
            if framework in {"IOKit", "CoreServices", "DiskArbitration", "AppKit"}:
                raise RuntimeError(f"A dependency still requires a macOS framework: {framework}")
            command.extend([flag, framework])
            index += 1
        elif flag.startswith("-l") and flag[2:] in SYSTEM_LIBRARIES:
            command.append(flag)
        elif flag.startswith("-Wl,") or flag == "-pthread":
            command.append(flag)
        index += 1
    run(command, env=env)


def build_target(target, root, jobs, configure_only=False):
    directory = root / target.identifier
    sdk_root = Path(xcrun(target.sdk, "--show-sdk-path"))
    clang = xcrun(target.sdk, "--find", "clang")
    clangxx = xcrun(target.sdk, "--find", "clang++")
    ar = xcrun(target.sdk, "--find", "ar")
    ranlib = xcrun(target.sdk, "--find", "ranlib")
    pkgconfig = shutil.which("pkg-config")
    fingerprint = hashlib.sha256()
    configuration_files = {Path(__file__).resolve(), REPOSITORY / "make/configure.py"}
    for pattern in ("make/**/*.defs", "contrib/**/module.defs", "contrib/**/*.patch"):
        configuration_files.update(REPOSITORY.glob(pattern))
    for path in sorted(configuration_files):
        fingerprint.update(path.relative_to(REPOSITORY).as_posix().encode())
        fingerprint.update(path.read_bytes())
    identity = {"target": target.triple, "sdk": str(sdk_root), "clang": clang,
                "sdk_version": xcrun(target.sdk, "--show-sdk-version"),
                "compiler_version": run([clang, "--version"], capture=True).splitlines()[0],
                "configuration_sha256": fingerprint.hexdigest(), "lto": False,
                "x265": True, "x265_bit_depths": list(X265_BIT_DEPTHS),
                "libdovi": False, "fdk_aac": False}
    identity_file = directory / "ios-build-identity.json"
    if identity_file.exists() and json.loads(identity_file.read_text()) != identity:
        raise RuntimeError(f"Build configuration changed for {directory}; use a fresh --build-root")
    directory.mkdir(parents=True, exist_ok=True)
    tools, cc, cxx, cmake, meson = toolchain_files(
        directory, target, sdk_root, clang, clangxx, ar, ranlib, pkgconfig,
    )
    host_cc, host_cxx = host_compiler_wrappers(
        directory, Path(xcrun("macosx", "--show-sdk-path")),
        xcrun("macosx", "--find", "clang"), xcrun("macosx", "--find", "clang++"),
    )
    env = os.environ.copy()
    # Do not inherit macOS SDK/flags or Homebrew pkg-config libraries.
    for name in ("CFLAGS", "CXXFLAGS", "CPPFLAGS", "LDFLAGS", "SDKROOT",
                 "MACOSX_DEPLOYMENT_TARGET", "CMAKE_PREFIX_PATH", "CPATH", "LIBRARY_PATH"):
        env.pop(name, None)
    env.update({"PATH": str(tools) + os.pathsep + env["PATH"], "CC": str(cc), "CXX": str(cxx),
                "CC_FOR_BUILD": str(host_cc), "CXX_FOR_BUILD": str(host_cxx), "AR": ar, "RANLIB": ranlib,
                "PKG_CONFIG_PATH": "", "PKG_CONFIG_LIBDIR": str(directory / "contrib/lib/pkgconfig"),
                "IPHONEOS_DEPLOYMENT_TARGET": target.minimum})
    command = [sys.executable, REPOSITORY / "make/configure.py", "--src", REPOSITORY,
               "--build", directory, "--force", "--disable-xcode", "--disable-gtk",
               "--arch", target.arch, "--ios", target.sdk, "--sysroot", sdk_root,
               "--minver", target.minimum, "--ios-cmake-toolchain", cmake,
               "--ios-meson-cross", meson, "--ios-host-cc", host_cc,
               "--cc", cc, "--ar", ar, "--ranlib", ranlib,
               "--enable-x265", "--disable-numa", "--disable-libdovi", "--disable-fdk-aac",
               "--disable-nvenc", "--disable-nvdec", "--disable-qsv", "--disable-vce",
               "--enable-ffmpeg-aac", "--enable-ffmpeg-prores", "--optimize", "speed", "--lto", "off"]
    run(command, cwd=REPOSITORY, env=env)
    write_text(identity_file, json.dumps(identity, indent=2) + "\n")
    if configure_only:
        return None
    # Prove the requested x265 multilib compiles for this Apple platform before
    # building the rest of the engine's independent contrib dependencies.
    run(["make", "-C", directory, f"-j{jobs}", "x265.install"], env=env)
    x265_archive = directory / "contrib/lib/libx265.a"
    x265_objects = verify_archive_platform(x265_archive, target)
    verify_x265_multilib(x265_archive, target)
    write_text(directory / "x265-build-manifest.json", json.dumps({**identity,
        "archive": x265_archive.relative_to(directory).as_posix(),
        "verified_objects": x265_objects,
        "verified_api_definitions_bit_depths": list(X265_BIT_DEPTHS),
        "validation": "Mach-O platform/architecture and static API definitions; runtime encoding not executed",
    }, indent=2) + "\n")
    print(f"Verified {x265_objects} {target.identifier} x265 objects and 8/10/12-bit APIs", flush=True)
    # libhb has explicit contrib install prerequisites. Its Metal shaders have a
    # native bin2c prerequisite, avoiding a target helper execution on the Mac.
    run(["make", "-C", directory, f"-j{jobs}", "libhb.build"], env=env)
    archives, flags = dependency_archives(directory, env)
    for archive in archives:
        print(f"Verified {verify_archive_platform(archive, target)} {target.identifier} objects in {archive}")
    package = directory / "package"
    package.mkdir(exist_ok=True)
    headers = package / "Headers"
    shutil.copytree(directory / "contrib/include", headers, dirs_exist_ok=True)
    shutil.copytree(directory / "libhb/handbrake", headers / "handbrake", dirs_exist_ok=True)
    write_engine_module(headers)
    merged = package / "libHandBrakeEngine.a"
    run(["xcrun", "--sdk", target.sdk, "libtool", "-static", "-o", merged, *archives])
    actual_arches = run(["xcrun", "lipo", "-archs", merged], capture=True).split()
    if actual_arches != [target.arch]:
        raise RuntimeError(f"Unexpected architectures in {merged}: {actual_arches}")
    verify_archive_platform(merged, target)
    verify_x265_multilib(merged, target)
    link_smoke(directory, target, cc, env, merged, headers, flags)
    write_text(package / "build-manifest.json", json.dumps({**identity,
               "archives": [str(p) for p in archives], "link_flags": flags}, indent=2) + "\n")
    return merged, headers


def package_xcframework(results, root, destination):
    # Combine simulator architectures only; never lipo device+simulator arm64.
    libraries = []
    for sdk in ("iphoneos", "iphonesimulator"):
        matching = [(target, result) for target, result in results if target.sdk == sdk]
        if not matching:
            continue
        if len(matching) == 1:
            libraries.append(matching[0][1])
        else:
            universal = root / "simulator-universal/libHandBrakeEngine.a"
            universal.parent.mkdir(parents=True, exist_ok=True)
            run(["xcrun", "lipo", "-create", *[result[0] for _, result in matching], "-output", universal])
            libraries.append((universal, matching[0][1][1]))
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".handbrake-package-", dir=destination.parent) as staging:
        candidate = Path(staging) / destination.name
        command = ["xcodebuild", "-create-xcframework"]
        for archive, headers in libraries:
            command.extend(["-library", archive, "-headers", headers])
        command.extend(["-output", candidate])
        run(command)
        # Keep the previous artifact until the replacement is complete.
        previous = Path(staging) / "previous.xcframework"
        if destination.exists():
            destination.rename(previous)
        try:
            candidate.rename(destination)
        except Exception:
            if previous.exists():
                previous.rename(destination)
            raise
    notices = destination.parent / "HandBrakeEngine-Licenses"
    notices.mkdir(exist_ok=True)
    for name in ("COPYING", "AUTHORS.markdown", "THANKS.markdown", "LICENSE"):
        source = REPOSITORY / name
        if source.is_file():
            shutil.copy2(source, notices / name)
    # Preserve upstream notices from the exact unpacked dependency releases.
    for dependency in (root / results[0][0].identifier / "contrib").iterdir():
        if dependency.is_dir():
            for path in dependency.glob("*/**/*"):
                if path.is_file() and re.match(r"(?i)^(copying|license|notice|copyright)(\..*)?$", path.name):
                    relative = path.relative_to(dependency)
                    output = notices / dependency.name / relative
                    output.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(path, output)
    print(f"Created {destination}")


def parse_arguments(arguments=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-root", type=Path, default=REPOSITORY / "ios/build/engine")
    parser.add_argument("--output", type=Path, default=REPOSITORY / "ios/Artifacts/HandBrakeEngine.xcframework")
    parser.add_argument("--minimum-ios", default="17.0")
    parser.add_argument("--simulator-arch", action="append", choices=("arm64", "x86_64"))
    parser.add_argument("--device-only", action="store_true")
    parser.add_argument("--configure-only", action="store_true")
    parser.add_argument("--jobs", type=int, default=min(os.cpu_count() or 2, 8))
    parser.add_argument("--plan", action="store_true", help="print target/dependency plan without running Apple tools")
    args = parser.parse_args(arguments)
    if not re.fullmatch(r"\d+(?:\.\d+){0,2}", args.minimum_ios) or int(args.minimum_ios.split('.')[0]) < 17:
        parser.error("--minimum-ios must be iOS 17 or later")
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    if args.device_only and args.simulator_arch:
        parser.error("--device-only cannot be combined with --simulator-arch")
    return args


def main(arguments=None):
    args = parse_arguments(arguments)
    targets = [Target("iphoneos", "arm64", args.minimum_ios)]
    if not args.device_only:
        targets += [Target("iphonesimulator", arch, args.minimum_ios)
                    for arch in dict.fromkeys(args.simulator_arch or ["arm64"])]
    if args.plan:
        print(json.dumps({"host": platform.system(), "targets": [target.triple for target in targets],
              "output": str(args.output), "engine": "libhb/libhandbrake.a", "pkgconfig_packages": PACKAGES,
              "frameworks": FRAMEWORKS, "x265_bit_depths": X265_BIT_DEPTHS,
              "disabled_optional_dependencies": ["libdovi", "fdk-aac"],
              "validation": "compile and static link only; device/runtime tests require Xcode and a device"}, indent=2))
        return 0
    if platform.system() != "Darwin":
        raise RuntimeError("An iOS engine build requires macOS with full Xcode and iOS SDKs. Use --plan on this host.")
    for tool in ("xcrun", "xcodebuild", "make", "autoconf", "automake", "libtool", "pkg-config", "cmake", "meson", "ninja", "nasm"):
        if not shutil.which(tool):
            raise RuntimeError(f"Missing build tool: {tool}. See ios/BUILDING.md.")
    root, output = args.build_root.resolve(), args.output.resolve()
    # Upstream make uses whitespace-separated paths throughout its rules.
    for path in (REPOSITORY, root, output):
        if any(character.isspace() for character in str(path)):
            raise RuntimeError(f"HandBrake's make build requires paths without whitespace: {path}")
    results = [(target, build_target(target, root, args.jobs, args.configure_only)) for target in targets]
    if not args.configure_only:
        package_xcframework(results, root, output)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (RuntimeError, subprocess.CalledProcessError) as error:
        print(f"build-engine: {error}", file=sys.stderr)
        sys.exit(1)
